"""Patient Health Prediction Application.

Flask backend with SQLite storage. Remarks are generated by calling the
Health Risk Prediction API (health_api.py, a separate REST service) with the
patient's age and blood test values.
"""
import os
import re
import sqlite3
from datetime import date, datetime

import requests
from flask import Flask, flash, g, redirect, render_template, request, url_for

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(BASE_DIR, "patients.db")

HEALTH_API_URL = os.environ.get("HEALTH_API_URL", "http://127.0.0.1:5001/predict")

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "dev-only-key")

EMAIL_RE = re.compile(r"^[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}$")
DATE_RE = re.compile(r"^\d{2}/\d{2}/\d{4}$")
NAME_RE = re.compile(r"^[A-Za-z][A-Za-z .'-]{1,99}$")

# Plausible physiological limits used to catch typing mistakes.
LIMITS = {
    "glucose": ("Glucose", "mg/dL", 20, 800),
    "haemoglobin": ("Haemoglobin", "g/dL", 3, 25),
    "cholesterol": ("Cholesterol", "mg/dL", 50, 600),
}


# ----------------------------------------------------------------- database
def get_db():
    if "db" not in g:
        g.db = sqlite3.connect(DB_PATH)
        g.db.row_factory = sqlite3.Row
    return g.db


@app.teardown_appcontext
def close_db(_exc):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    with sqlite3.connect(DB_PATH) as con:
        con.execute(
            """CREATE TABLE IF NOT EXISTS patients (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                full_name TEXT NOT NULL,
                dob TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE COLLATE NOCASE,
                glucose REAL NOT NULL,
                haemoglobin REAL NOT NULL,
                cholesterol REAL NOT NULL,
                remarks TEXT,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP
            )"""
        )


# --------------------------------------------------------------- validation
def validate(form, patient_id=None):
    """Return (clean_data, errors). Errors is a dict of field -> message."""
    errors, data = {}, {}

    name = " ".join(form.get("full_name", "").split())
    if not name:
        errors["full_name"] = "Full name is required."
    elif not NAME_RE.match(name):
        errors["full_name"] = "Name may contain letters, spaces, . ' - only."
    data["full_name"] = name

    dob_text = form.get("dob", "").strip()
    data["dob_text"] = dob_text
    if not dob_text:
        errors["dob"] = "Date of birth is required."
    elif not DATE_RE.match(dob_text):
        errors["dob"] = "Date must be in dd/mm/yyyy format (use '/' as separator)."
    else:
        try:
            dob = datetime.strptime(dob_text, "%d/%m/%Y").date()
            if dob > date.today():
                errors["dob"] = "Date of birth cannot be in the future."
            elif dob.year < 1900:
                errors["dob"] = "Date of birth must be 1900 or later."
            else:
                data["dob"] = dob.isoformat()
        except ValueError:
            errors["dob"] = "This is not a real calendar date."

    email = form.get("email", "").strip()
    if not email:
        errors["email"] = "Email address is required."
    elif not EMAIL_RE.match(email):
        errors["email"] = "Enter a valid email address, e.g. name@example.com."
    else:
        # Emails must be unique; when editing, ignore the record being edited.
        row = get_db().execute(
            "SELECT id FROM patients WHERE email = ? AND id != ?",
            (email, patient_id or -1),
        ).fetchone()
        if row:
            errors["email"] = "A patient with this email already exists."
    data["email"] = email

    for key, (label, unit, lo, hi) in LIMITS.items():
        raw = form.get(key, "").strip()
        data[key + "_text"] = raw
        if not raw:
            errors[key] = f"{label} is required."
            continue
        try:
            value = float(raw)
        except ValueError:
            errors[key] = f"{label} must be a number."
            continue
        if value != value or value in (float("inf"), float("-inf")):
            errors[key] = f"{label} must be a valid number."
        elif not lo <= value <= hi:
            errors[key] = f"{label} must be between {lo} and {hi} {unit}."
        else:
            data[key] = value
    return data, errors


# --------------------------------------------------------------- Health API
def generate_remarks(name, dob_iso, glucose, haemoglobin, cholesterol):
    """Call the Health Risk Prediction API. Returns remarks text or None."""
    age = (date.today() - date.fromisoformat(dob_iso)).days // 365
    try:
        resp = requests.post(
            HEALTH_API_URL,
            json={"age": age, "glucose": glucose,
                  "haemoglobin": haemoglobin, "cholesterol": cholesterol},
            timeout=10,
        )
        resp.raise_for_status()
        return resp.json()["remarks"]
    except (requests.RequestException, KeyError, ValueError):
        return None


def remarks_or_pending(*args):
    text = generate_remarks(*args)
    if text:
        return text
    return "Pending - Health API unavailable. Use 'Regenerate' to retry."


# -------------------------------------------------------------------- views
@app.template_filter("dmy")
def dmy(iso):
    return datetime.strptime(iso, "%Y-%m-%d").strftime("%d/%m/%Y")


@app.route("/")
def index():
    q = request.args.get("q", "").strip()
    sql, params = "SELECT * FROM patients", ()
    if q:
        sql += " WHERE full_name LIKE ? OR email LIKE ?"
        params = (f"%{q}%", f"%{q}%")
    rows = get_db().execute(sql + " ORDER BY id ASC", params).fetchall()
    return render_template("index.html", patients=rows, q=q)


@app.route("/add", methods=["GET", "POST"])
def add():
    if request.method == "POST":
        data, errors = validate(request.form)
        if errors:
            return render_template("form.html", mode="add", data=data, errors=errors), 400
        remarks = remarks_or_pending(
            data["full_name"], data["dob"], data["glucose"],
            data["haemoglobin"], data["cholesterol"],
        )
        db = get_db()
        db.execute(
            "INSERT INTO patients (full_name, dob, email, glucose, haemoglobin, cholesterol, remarks) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (data["full_name"], data["dob"], data["email"], data["glucose"],
             data["haemoglobin"], data["cholesterol"], remarks),
        )
        db.commit()
        flash(f"Record for {data['full_name']} saved.", "success")
        return redirect(url_for("index"))
    return render_template("form.html", mode="add", data={}, errors={})


@app.route("/edit/<int:pid>", methods=["GET", "POST"])
def edit(pid):
    db = get_db()
    row = db.execute("SELECT * FROM patients WHERE id = ?", (pid,)).fetchone()
    if row is None:
        flash("Record not found.", "danger")
        return redirect(url_for("index"))

    if request.method == "POST":
        data, errors = validate(request.form, patient_id=pid)
        if errors:
            return render_template("form.html", mode="edit", pid=pid, data=data, errors=errors), 400
        remarks = remarks_or_pending(
            data["full_name"], data["dob"], data["glucose"],
            data["haemoglobin"], data["cholesterol"],
        )
        db.execute(
            "UPDATE patients SET full_name=?, dob=?, email=?, glucose=?, haemoglobin=?, "
            "cholesterol=?, remarks=? WHERE id=?",
            (data["full_name"], data["dob"], data["email"], data["glucose"],
             data["haemoglobin"], data["cholesterol"], remarks, pid),
        )
        db.commit()
        flash("Record updated.", "success")
        return redirect(url_for("index"))

    data = {
        "full_name": row["full_name"],
        "dob_text": dmy(row["dob"]),
        "email": row["email"],
        "glucose_text": row["glucose"],
        "haemoglobin_text": row["haemoglobin"],
        "cholesterol_text": row["cholesterol"],
    }
    return render_template("form.html", mode="edit", pid=pid, data=data, errors={})


@app.route("/regenerate/<int:pid>", methods=["POST"])
def regenerate(pid):
    db = get_db()
    row = db.execute("SELECT * FROM patients WHERE id = ?", (pid,)).fetchone()
    if row:
        remarks = remarks_or_pending(
            row["full_name"], row["dob"], row["glucose"],
            row["haemoglobin"], row["cholesterol"],
        )
        db.execute("UPDATE patients SET remarks=? WHERE id=?", (remarks, pid))
        db.commit()
        flash("Remarks refreshed.", "success")
    return redirect(url_for("index"))


@app.route("/delete/<int:pid>", methods=["POST"])
def delete(pid):
    db = get_db()
    db.execute("DELETE FROM patients WHERE id = ?", (pid,))
    db.commit()
    flash("Record deleted.", "success")
    return redirect(url_for("index"))


init_db()

if __name__ == "__main__":
    app.run(debug=False, port=5000)
